/*
 * n: number
 * e: empty string
 * $: end of input
 */

// -------- Top down parser --------

/*
 * Top down backtrack free (predictive) grammar
 * A0 -> U B0 A1
 * U  -> + | - | e
 * A1 -> + B0 A1 | - B0 A1 | e
 * B0 -> C0 B1
 * B1 -> * C0 B1 | / C0 B1 | e
 * C0 -> X C1
 * C1 -> ^ C0 | e
 * X  -> n | ( A0 )
 */

/*
 * FIRST
 * '$'  : { '$' }
 * '('  : { '(' }
 * ')'  : { ')' }
 * '*'  : { '*' }
 * '+'  : { '+' }
 * '-'  : { '-' }
 * '/'  : { '/' }
 * 'A0' : { '(', '+', '-', 'n' }
 * 'A1' : { '+', '-', 'e' }
 * 'B0' : { '(', 'n' }
 * 'B1' : { '*', '/', 'e' }
 * 'C0' : { '(', 'n' }
 * 'C1' : { '^', 'e' }
 * 'S'  : { '+', '-', 'e' }
 * 'X'  : { '(', 'n' }
 * '^'  : { '^' }
 * 'e'  : { 'e' }
 * 'n'  : { 'n' }
 *
 * FOLLOW
 * 'A0' : { '$', ')' }
 * 'A1' : { '$', ')' }
 * 'B0' : { '$', ')', '+', '-' }
 * 'B1' : { '$', ')', '+', '-' }
 * 'C0' : { '$', ')', '*', '+', '-', '/' }
 * 'C1' : { '$', ')', '*', '+', '-', '/' }
 * 'S'  : { '(', 'n' }
 * 'X'  : { '$', ')', '*', '+', '-', '/', '^' }
 *
 * AUGMENTED FIRST
 * 'A0 -> S B0 A1' : { '(', '+', '-', 'n' }
 * 'A1 -> + B0 A1' : { '+' }
 * 'A1 -> - B0 A1' : { '-' }
 * 'A1 -> e'       : { '$', ')', 'e' }
 * 'B0 -> C0 B1'   : { '(', 'n' }
 * 'B1 -> * C0 B1' : { '*' }
 * 'B1 -> / C0 B1' : { '/' }
 * 'B1 -> e'       : { '$', ')', '+', '-', 'e' }
 * 'C0 -> X C1'    : { '(', 'n' }
 * 'C1 -> ^ C0'    : { '^' }
 * 'C1 -> e'       : { '$', ')', '*', '+', '-', '/', 'e' }
 * 'S -> +'        : { '+' }
 * 'S -> -'        : { '-' }
 * 'S -> e'        : { '(', 'e', 'n' }
 * 'X -> ( A0 )'   : { '(' }
 * 'X -> n'        : { 'n' }
 */

//
int recursive_descent_parser(const gvec_t *tokens, err_msg_t *err);

